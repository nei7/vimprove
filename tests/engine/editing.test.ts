import { describe, expect, test } from 'vitest'
import { edit, run } from './helpers'

describe('insert mode', () => {
  test('i a I A o O', () => {
    expect(edit('fo|o', 'iX<Esc>')).toBe('fo|Xo')
    expect(edit('fo|o', 'aX<Esc>')).toBe('foo|X')
    expect(edit('  fo|o', 'IX<Esc>')).toBe('  |Xfoo')
    expect(edit('  fo|o', 'gIX<Esc>')).toBe('|X  foo')
    expect(edit('f|oo', 'AX<Esc>')).toBe('foo|X')
    expect(edit('  f|oo\nbar', 'oX<Esc>')).toBe('  foo\n  |X\nbar')
    expect(edit('  f|oo\nbar', 'OX<Esc>')).toBe('  |X\n  foo\nbar')
    expect(edit('  f|oo', 'o<Esc>')).toBe('  foo\n|')
    expect(edit('|', 'ihello<Esc>')).toBe('hell|o')
    expect(edit('|', 'iab<CR>cd<Esc>')).toBe('ab\nc|d')
    expect(edit('  a|b', 'i<CR><Esc>')).toBe('  a\n | b')
    expect(edit('  a|b', 'a<CR><Esc>')).toBe('  ab\n|')
  })
  test('counts', () => {
    expect(edit('|', '3ia<Esc>')).toBe('aa|a')
    expect(edit('|x', '2Aab<Esc>')).toBe('xaba|b')
    expect(edit('|a', '2ob<Esc>')).toBe('a\nb\n|b')
  })
  test('backspace, <C-w>, <C-u>, <Del>', () => {
    expect(edit('foo|', 'a<BS><BS>x<Esc>')).toBe('f|x')
    expect(edit('|a\nb', 'ji<BS><Esc>')).toBe('|ab')
    expect(edit('foo bar|', 'a<C-w>x<Esc>')).toBe('foo |x')
    expect(edit('foo bar|', 'a<C-w><C-w>x<Esc>')).toBe('|x')
    expect(edit('foo.bar|', 'a<C-w>x<Esc>')).toBe('foo.|x')
    expect(edit('foo|', 'abar<C-u>x<Esc>')).toBe('foo|x')
    expect(edit('  foo|', 'a<C-u>x<Esc>')).toBe('  |x')
    expect(edit('f|oo', 'i<Del><Esc>')).toBe('|fo')
  })
  test('<C-r> <C-t> <C-d> <C-o>', () => {
    expect(edit('|foo bar', 'yiwA <C-r>"<Esc>')).toBe('foo bar fo|o')
    expect(edit('|foo', 'A<C-t><Esc>')).toBe('  fo|o')
    expect(edit('    |foo', 'A<C-d><Esc>')).toBe('  fo|o')
    expect(edit('|foo bar', 'ix<C-o>$y<Esc>')).toBe('xfoo bar|y')
    expect(edit('|foo bar', 'A<C-o>0y<Esc>')).toBe('|yfoo bar')
  })
  test('<Tab> with expandtab', () => {
    expect(edit('|', 'i<Tab>x<Esc>')).toBe('  |x')
    expect(edit('|', 'i<Tab>x<Esc>', { shiftwidth: 4 })).toBe('    |x')
    expect(edit('|', 'i<Tab>x<Esc>', { expandtab: false })).toBe('\t|x')
  })
})

describe('undo / redo', () => {
  test('u and <C-r>', () => {
    expect(edit('|foo bar', 'dwu')).toBe('|foo bar')
    expect(edit('|foo bar', 'dwu<C-r>')).toBe('|bar')
    expect(edit('|foo bar', 'dwdwuu')).toBe('|foo bar')
    expect(edit('|foo bar', 'dwdw2u')).toBe('|foo bar')
    expect(edit('|foo', 'ciwhello<Esc>u')).toBe('|foo')
    expect(edit('|foo', 'ohello<CR>world<Esc>u')).toBe('|foo')
    expect(edit('|a\nb\nc', 'ddddu')).toBe('|b\nc')
    expect(edit('|a\nb\nc', ':%s/./x/<CR>u')).toBe('|a\nb\nc')
  })
  test('dot repeat is a single undo step', () => {
    expect(edit('|a a a', 'ciwb<Esc>w.w.uu')).toBe('b |a a')
  })
})

describe('dot repeat', () => {
  test('simple changes', () => {
    expect(edit('|a b c d', 'dw..')).toBe('|d')
    expect(edit('|a b c d', 'dw2.')).toBe('|d')
    expect(edit('|foo bar', 'xp.')).toBe('of|fo bar')
    expect(edit('|a\nb\nc\nd', 'A;<Esc>j.j.j.')).toBe('a;\nb;\nc;\nd|;')
    expect(edit('|foo bar foo', 'ciwx<Esc>ww.')).toBe('x bar |x')
    expect(edit('|a\nb\nc', 'ddj.')).toBe('|b')
    expect(edit('|foo foo foo', '*ciwbar<Esc>n.')).toBe('foo bar ba|r')
    expect(edit('|aaa', 'rbl.l.')).toBe('bb|b')
    expect(edit('|a\nb', '>>j.')).toBe('  a\n  |b')
    expect(edit('|ab', 'ix<Esc>l.')).toBe('x|xab')
    expect(edit('|a\nb', 'yyp.')).toBe('a\na\n|a\nb')
    expect(edit('|a b', 'cwx<Esc>w.')).toBe('x |x')
  })
  test('dot after search operator', () => {
    expect(edit('|a foo b foo', 'd/foo<CR>w.')).toBe('foo |foo')
  })
  test('dot after visual operation', () => {
    expect(edit('|abcdef', 'vldl.')).toBe('c|f')
    expect(edit('|a\nb\nc\nd', 'Vjdj.')).toBe('|c')
    expect(edit('|a\nb\nc\nd', 'Vj>.')).toBe('    |a\n    b\nc\nd')
  })
})

describe('visual mode', () => {
  test('v with motions and operators', () => {
    expect(edit('|foo bar', 'ved')).toBe('| bar')
    expect(edit('|foo bar', 'vey')).toBe('|foo bar')
    expect(edit('|foo bar', 'veyP')).toBe('fo|ofoo bar')
    expect(edit('foo |bar', 'vbd')).toBe('|ar')
    expect(edit('|foo bar', 'vecX<Esc>')).toBe('|X bar')
    expect(edit('|foo bar', 'v$d')).toBe('|')
    expect(edit('|foo\nbar', 'v$d')).toBe('|bar')
    expect(edit('f|oo bar', 'viwd')).toBe('| bar')
    expect(edit('f|oo bar', 'vawd')).toBe('|bar')
    expect(edit('x = "a|b"', 'vi"d')).toBe('x = "|"')
    expect(edit('f(a|b)', 'va(d')).toBe('|f')
    expect(edit('|foo bar', 'veU')).toBe('|FOO bar')
    expect(edit('|foo bar', 've~')).toBe('|FOO bar')
    expect(edit('|foo bar', 'verx')).toBe('|xxx bar')
    expect(edit('|foo bar', 'veJ')).toBe('fo|o bar')
    expect(edit('|foo\nbar', 'vjJ')).toBe('foo| bar')
    expect(edit('|abc', 'lvlo')).toBe('a|bc')
    expect(edit('|abc', 'lvlohd')).toBe('|')
  })
  test('V linewise', () => {
    expect(edit('|a\nb\nc', 'Vjd')).toBe('|c')
    expect(edit('|a\nb\nc', 'Vjy')).toBe('|a\nb\nc')
    expect(edit('|a\nb\nc', 'VjyP')).toBe('|a\nb\na\nb\nc')
    expect(edit('|a\nb\nc', 'Vj>')).toBe('  |a\n  b\nc')
    expect(edit('|a\nb\nc', 'Vj2>')).toBe('    |a\n    b\nc')
    expect(edit('  |a\n  b\nc', 'VjcX<Esc>')).toBe('  |X\nc')
    expect(edit('|a\nb\nc', 'vjD')).toBe('|c')
    expect(edit('|a\nb\nc', 'vjX')).toBe('|c')
    expect(edit('|a\nb\nc', 'VjJ')).toBe('a| b\nc')
    expect(edit('a\nb|\n\nc', 'vipd')).toBe('|\nc')
    expect(edit('|a\nb\nc', 'VGd')).toBe('|')
  })
  test('visual block', () => {
    expect(edit('|abc\nabc\nabc', '<C-v>jjd')).toBe('|bc\nbc\nbc')
    expect(edit('|abc\nabc\nabc', '<C-v>jjld')).toBe('|c\nc\nc')
    expect(edit('|abc\nabc\nabc', '<C-v>jjI// <Esc>')).toBe('|// abc\n// abc\n// abc')
    expect(edit('|abc\nabc\nabc', '<C-v>jj$A;<Esc>')).toBe('abc|;\nabc;\nabc;')
    expect(edit('|abc\nab\nabc', '<C-v>jj$A;<Esc>')).toBe('abc|;\nab;\nabc;')
    expect(edit('|abc\nabc\nabc', 'l<C-v>jjA-<Esc>')).toBe('ab|-c\nab-c\nab-c')
    expect(edit('|abc\nabc\nabc', '<C-v>jjcX<Esc>')).toBe('|Xbc\nXbc\nXbc')
    expect(edit('|abc\nabc\nabc', '<C-v>jjlrx')).toBe('|xxc\nxxc\nxxc')
    expect(edit('|abc\nabc\nabc', '<C-v>jjly')).toBe('|abc\nabc\nabc')
    expect(edit('|abc\nabc\nabc', '<C-v>jjly$p')).toBe('abc|ab\nabcab\nabcab')
    expect(edit('|abc\nabc\nabc', '<C-v>jjlU')).toBe('|ABc\nABc\nABc')
    expect(edit('|abc\nabc\nabc', 'l<C-v>jjD')).toBe('|a\na\na')
    expect(edit('|abc\na\nabc', '<C-v>jjlI-<Esc>')).toBe('|-abc\n-a\n-abc')
    expect(edit('|a 1\nb 1\nc 1', '<C-v>jj$g<C-a>')).toBe('|a 2\nb 3\nc 4')
  })
  test('visual put', () => {
    expect(edit('|foo bar', 'yiwwviwp')).toBe('foo fo|o')
    expect(edit('|foo bar', 'yiwwviwpP')).toBe('foo foba|ro')
    expect(edit('|a\nb\nc', 'yyjVp')).toBe('a\n|a\nc')
    expect(edit('|a\nb', 'yiwjVp')).toBe('a\n|a')
    expect(edit('|a\nb c', 'yyjwviwp')).toBe('a\nb \n|a\n')
  })
  test('gv and marks', () => {
    expect(edit('|abc def', 'vey<Esc>gvd')).toBe('| def')
    expect(edit('|a\nb\nc', "Vj<Esc>G'<")).toBe('|a\nb\nc')
    expect(edit('|a\nb\nc', 'Vj:d<CR>')).toBe('|c')
  })
  test('text objects in visual extend selection', () => {
    expect(edit('f(a, |b)', 'vi(d')).toBe('f(|)')
    expect(edit('f() {\n  |a\n}', 'vi{d')).toBe('f() {\n|}')
    expect(edit('|a\nb\n\nc', 'vipd')).toBe('|\nc')
  })
})

describe('ex commands', () => {
  test(':s and :%s', () => {
    expect(edit('|foo foo\nfoo', ':s/foo/bar/<CR>')).toBe('|bar foo\nfoo')
    expect(edit('|foo foo\nfoo', ':s/foo/bar/g<CR>')).toBe('|bar bar\nfoo')
    expect(edit('|foo foo\nfoo', ':%s/foo/bar/g<CR>')).toBe('bar bar\n|bar')
    expect(edit('|a1 a2', ':s/a\\(\\d\\)/b\\1/g<CR>')).toBe('|b1 b2')
    expect(edit('|a1 a2', ':s/\\va(\\d)/b\\1/g<CR>')).toBe('|b1 b2')
    expect(edit('|foo_bar', ':s/_\\(\\w\\)/\\u\\1/g<CR>')).toBe('|fooBar')
    expect(edit('|fooBar', ':s/\\(\\u\\)/_\\l\\1/g<CR>')).toBe('|foo_bar')
    expect(edit('|a,b', ':s/,/\\r/<CR>')).toBe('a\n|b')
    expect(edit('|a b', ':s/ /&&/<CR>')).toBe('|a  b')
    expect(edit('|a\nb\nc', ':2,3s/$/;/<CR>')).toBe('a\nb;\n|c;')
    expect(edit('|a\nb\nc', ':.,+1s/$/;/<CR>')).toBe('a;\n|b;\nc')
    expect(edit('|a\nb\nc', 'Vj:s/$/;/<CR>')).toBe('a;\n|b;\nc')
    expect(edit('|path/to', ':s#/#.#<CR>')).toBe('|path.to')
    expect(edit('|foo Foo', ':s/foo/x/gi<CR>')).toBe('|x x')
    expect(edit('|foo foo', '/foo<CR>:s//x/g<CR>')).toBe('|x x')
    expect(edit('|a a\na a', ':s/a/b/<CR>j&')).toBe('b a\n|b a')
    expect(edit('|a a\na a', ':s/a/b/g<CR>jg&')).toBe('b b\n|b b')
    expect(edit('|"a" "b"', ":s/\"/'/g<CR>")).toBe("|'a' 'b'")
    expect(edit('|a.b', ':s/\\./-/<CR>')).toBe('|a-b')
    expect(edit('|a.b', ':s/./-/g<CR>')).toBe('|---')
    expect(edit('|f(x)', ':s/f(\\(.*\\))/g[\\1]/<CR>')).toBe('|g[x]')
    expect(edit('|foo', ':s/x/y/<CR>')).toBe('|foo')
  })
  test(':d :y :m :t :j :> :<', () => {
    expect(edit('|a\nb\nc\nd', ':2,3d<CR>')).toBe('a\n|d')
    expect(edit('|a\nb\nc\nd', ':2d<CR>')).toBe('a\n|c\nd')
    expect(edit('|a\nb\nc\nd', ':%d<CR>')).toBe('|')
    expect(edit('|a\nb\nc', ':m$<CR>')).toBe('b\nc\n|a')
    expect(edit('|a\nb\nc', ':m+1<CR>')).toBe('b\n|a\nc')
    expect(edit('a\nb\n|c', ':m0<CR>')).toBe('|c\na\nb')
    expect(edit('a\nb\n|c', ':m-2<CR>')).toBe('a\n|c\nb')
    expect(edit('|a\nb\nc', ':1,2m$<CR>')).toBe('c\na\n|b')
    expect(edit('|a\nb', ':t.<CR>')).toBe('a\n|a\nb')
    expect(edit('|a\nb', ':t$<CR>')).toBe('a\nb\n|a')
    expect(edit('|a\nb', ':co0<CR>')).toBe('|a\na\nb')
    expect(edit('|a\nb\nc', ':1,3j<CR>')).toBe('a b| c')
    expect(edit('|a\nb\nc', ':j<CR>')).toBe('a| b\nc')
    expect(edit('|a\nb\nc', ':%><CR>')).toBe('  a\n  b\n  |c')
    expect(edit('  |a\n  b', ':%<<CR>')).toBe('a\n|b')
    expect(edit('|a\nb\nc', ':2<CR>')).toBe('a\n|b\nc')
    expect(edit('|a\nb\nc', ':$<CR>')).toBe('a\nb\n|c')
    expect(edit('|a\nb\nc', ':2y<CR>p')).toBe('a\nb\n|b\nc')
  })
  test(':g and :v', () => {
    expect(edit('|a\nlog(1)\nb\nlog(2)', ':g/log/d<CR>')).toBe('a\n|b')
    expect(edit('|a\nlog(1)\nb\nlog(2)', ':v/log/d<CR>')).toBe('log(1)\n|log(2)')
    expect(edit('|a\nlog(1)\nb\nlog(2)', ':g!/log/d<CR>')).toBe('log(1)\n|log(2)')
    expect(edit('|a\nb\nc', ':g/./norm A;<CR>')).toBe('a;\nb;\nc|;')
    expect(edit('|x\na\nx', ':g/x/s/x/y/<CR>')).toBe('y\na\n|y')
    expect(edit('|a\nb\nc', ':g/^/m0<CR>')).toBe('|c\nb\na')
  })
  test(':norm and :sort', () => {
    expect(edit('|a\nb\nc', ':%norm A,<CR>')).toBe('a,\nb,\nc|,')
    expect(edit('|a\nb\nc', ':%norm Ix<CR>')).toBe('xa\nxb\n|xc')
    expect(edit('|a\nb', ':norm dd<CR>')).toBe('|b')
    expect(edit('|c\na\nb', ':sort<CR>')).toBe('|a\nb\nc')
    expect(edit('|c\na\nb', ':sort!<CR>')).toBe('|c\nb\na')
    expect(edit('|b\na\nb', ':sort u<CR>')).toBe('|a\nb')
    expect(edit('|x10\nx9\nx100', ':sort n<CR>')).toBe('|x9\nx10\nx100')
    expect(edit('|z\nB\na', ':sort i<CR>')).toBe('|a\nB\nz')
    expect(edit('|z\nx\ny\na', ':1,3sort<CR>')).toBe('|x\ny\nz\na')
  })
  test(':set, :noh, :w, errors', () => {
    const r = run('a\n b', [0, 0], ':set sw=4<CR>>>')
    expect(r.text).toBe('    a\n b')
    const r2 = run('a', [0, 0], ':foo<CR>')
    expect(r2.vim.message).toMatch(/E492/)
    const r3 = run('a', [0, 0], ':w<CR>')
    expect(r3.vim.events.some((e) => e.type === 'write')).toBe(true)
    const r4 = run('a', [0, 0], '/a<CR>:noh<CR>')
    expect(r4.vim.hlsearch).toBe(false)
    const r5 = run('Foo foo', [0, 0], ':set ic<CR>/FOO<CR>')
    expect(r5.cursor).toEqual([0, 4])
  })
})

describe('macros', () => {
  test('record and replay', () => {
    expect(edit('|a\nb\nc', 'qaA;<Esc>jq2@a')).toBe('a;\nb;\nc|;')
    expect(edit('|a\nb\nc\nd', 'qaA;<Esc>jq@a@@')).toBe('a;\nb;\nc;\n|d')
    expect(edit('|1\n1\n1', 'qa<C-a>jq10@a')).toBe('2\n2\n|2')
    expect(edit('|a b c', 'qqdwq2@q')).toBe('|')
    const r = run('a', [0, 0], 'qaxq')
    expect(r.vim.getRegister('a')!.lines).toEqual(['x'])
    expect(r.vim.recording).toBeNull()
  })
})

describe('events', () => {
  test('command events carry names and keys', () => {
    const r = run('foo bar baz "qux"', [0, 0], '')
    const ev = r.vim.feedKeys('2dw')
    const cmds = ev.filter((e) => e.type === 'command')
    expect(cmds).toHaveLength(1)
    expect(cmds[0]).toMatchObject({ name: 'dw', keys: ['2', 'd', 'w'], count: 2, hasCount: true, changed: true })
    const ev2 = r.vim.feedKeys('ci"')
    expect(ev2.filter((e) => e.type === 'invalid')).toHaveLength(0)
    expect(ev2.filter((e) => e.type === 'command')[0]).toMatchObject({ name: 'ci"', kind: 'operator' })
    const ev3 = r.vim.feedKeys('<Esc>')
    expect(ev3.some((e) => e.type === 'insert-session')).toBe(true)
    expect(r.vim.text).toBe('baz ""')
  })
  test('invalid sequences are reported and reset', () => {
    const r = run('foo', [0, 0], '')
    const ev = r.vim.feedKeys('dq')
    expect(ev.some((e) => e.type === 'invalid')).toBe(true)
    expect(r.vim.pending).toEqual([])
  })
})
